/*
 * Encrypted, account-bound session storage (TurnoControl 0.3.0, phase 4B.3).
 *  - One file per account under noBackupFilesDir/sessions, named by the opaque storage key (never the raw id).
 *  - AES-256-GCM with a non-exportable Android Keystore key per account; the IV is generated by the cipher for every
 *    write (never reused) and the account id is authenticated as AAD, so A's file can never decrypt as B's.
 *  - Writes are atomic (temporary file + atomic move): an interrupted replacement leaves the old or the new session.
 *  - Any unreadable session means "sign in again"; it is never treated as authorization, and the account's calendar
 *    database is never touched. No secret is logged or placed in an exception message.
 */

/** The key for this alias no longer exists or was invalidated (e.g. lock-screen change, restore to another device). */
class SessionKeyUnavailableException : Exception("Clave de sesión no disponible.")

/** Authenticated-encryption boundary. Production: [KeystoreSessionCipher]; JVM tests: an AES-GCM double. */
interface SessionCipher {
    /** Returns IV and ciphertext; the IV must be freshly generated for every call. */
    fun encrypt(alias: String, plaintext: ByteArray, aad: ByteArray): Pair<ByteArray, ByteArray>
    /** Throws [SessionKeyUnavailableException] for a missing or invalidated key and [AEADBadTagException] for tampering. */
    fun decrypt(alias: String, iv: ByteArray, ciphertext: ByteArray, aad: ByteArray): ByteArray
    fun deleteKey(alias: String)
}

/** Android Keystore implementation. Not executable on the JVM; it needs validation on an Android device or emulator. */
class KeystoreSessionCipher : SessionCipher {
    private val store: KeyStore get() = KeyStore.getInstance("AndroidKeyStore").apply { load(null) }

    private fun existingKey(alias: String): SecretKey? = (store.getEntry(alias, null) as? KeyStore.SecretKeyEntry)?.secretKey

    private fun createKey(alias: String): SecretKey {
        fun spec(strongBox: Boolean) = android.security.keystore.KeyGenParameterSpec.Builder(alias,
            android.security.keystore.KeyProperties.PURPOSE_ENCRYPT or android.security.keystore.KeyProperties.PURPOSE_DECRYPT)
            .setBlockModes(android.security.keystore.KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(android.security.keystore.KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .setRandomizedEncryptionRequired(true) // The Keystore generates every IV: a caller can never reuse one.
            .apply { if (strongBox && android.os.Build.VERSION.SDK_INT >= 28) setIsStrongBoxBacked(true) }
            .build()
        val generator = KeyGenerator.getInstance(android.security.keystore.KeyProperties.KEY_ALGORITHM_AES, "AndroidKeyStore")
        return try { generator.init(spec(strongBox = true)); generator.generateKey() }
        catch (e: Exception) { generator.init(spec(strongBox = false)); generator.generateKey() } // No StrongBox: TEE-backed key.
    }

    override fun encrypt(alias: String, plaintext: ByteArray, aad: ByteArray): Pair<ByteArray, ByteArray> {
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        try { cipher.init(Cipher.ENCRYPT_MODE, existingKey(alias) ?: createKey(alias)) }
        catch (e: android.security.keystore.KeyPermanentlyInvalidatedException) { deleteKey(alias); cipher.init(Cipher.ENCRYPT_MODE, createKey(alias)) }
        cipher.updateAAD(aad)
        return cipher.iv to cipher.doFinal(plaintext)
    }

    override fun decrypt(alias: String, iv: ByteArray, ciphertext: ByteArray, aad: ByteArray): ByteArray {
        val key = existingKey(alias) ?: throw SessionKeyUnavailableException()
        val cipher = Cipher.getInstance("AES/GCM/NoPadding")
        try { cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(128, iv)) }
        catch (e: android.security.keystore.KeyPermanentlyInvalidatedException) { throw SessionKeyUnavailableException() }
        cipher.updateAAD(aad)
        return cipher.doFinal(ciphertext)
    }

    override fun deleteKey(alias: String) { runCatching { store.deleteEntry(alias) } }
}

enum class UnreadableReason { KEY_UNAVAILABLE, CORRUPTED, UNSUPPORTED_VERSION, WRONG_ACCOUNT }

sealed interface SessionLoad {
    data object Missing : SessionLoad
    data class Found(val session: AuthSession) : SessionLoad
    /** The stored session cannot be used: the user must sign in again. Never authorization. */
    data class RequiresSignIn(val reason: UnreadableReason) : SessionLoad
}

/** Session persistence keyed by validated account. Contains no authorization logic: validity is the provider's job. */
class EncryptedSessionVault(private val directory: File, private val cipher: SessionCipher) : com.turnocontrol.domain.auth.SessionPersistence {
    private companion object {
        val MAGIC = byteArrayOf('T'.code.toByte(), 'C'.code.toByte(), 'S'.code.toByte(), '1'.code.toByte())
        const val VERSION: Byte = 1
    }

    private fun key(account: AccountId) = StorageNamespace.forAccount(account).key
    private fun file(account: AccountId) = File(directory, key(account) + ".session")
    private fun alias(account: AccountId) = "turnocontrol-session-" + key(account)
    private fun aad(account: AccountId) = "turnocontrol/session/v1:${account.value}".toByteArray()

    override fun save(session: AuthSession) {
        val account = session.identity.accountId
        val plain = ByteArrayOutputStream().also { bytes -> DataOutputStream(bytes).use { out ->
            out.writeUTF(account.value); out.writeUTF(session.identity.method.name); out.writeUTF(session.identity.maskedEmail)
            out.writeLong(session.expiresAt.toEpochMilli()); out.writeUTF(session.handle)
        } }.toByteArray()
        try {
            val (iv, sealed) = cipher.encrypt(alias(account), plain, aad(account))
            val record = ByteArrayOutputStream().also { bytes -> DataOutputStream(bytes).use { out ->
                out.write(MAGIC); out.writeByte(VERSION.toInt()); out.writeByte(iv.size); out.write(iv); out.writeInt(sealed.size); out.write(sealed)
            } }.toByteArray()
            directory.mkdirs()
            val temporary = File(directory, file(account).name + ".tmp")
            temporary.writeBytes(record)
            Files.move(temporary.toPath(), file(account).toPath(), StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE)
        } finally { plain.fill(0) }
    }

    fun load(account: AccountId): SessionLoad {
        val target = file(account)
        if (!target.exists()) return SessionLoad.Missing
        val plain = try {
            DataInputStream(target.inputStream().buffered()).use { input ->
                val magic = ByteArray(4).also { input.readFully(it) }
                if (!magic.contentEquals(MAGIC) || input.readByte() != VERSION) return SessionLoad.RequiresSignIn(UnreadableReason.UNSUPPORTED_VERSION)
                val iv = ByteArray(input.readUnsignedByte()).also { input.readFully(it) }
                val length = input.readInt()
                if (length !in 1..65536) return SessionLoad.RequiresSignIn(UnreadableReason.CORRUPTED)
                val sealed = ByteArray(length).also { input.readFully(it) }
                cipher.decrypt(alias(account), iv, sealed, aad(account))
            }
        } catch (e: SessionKeyUnavailableException) { return SessionLoad.RequiresSignIn(UnreadableReason.KEY_UNAVAILABLE) }
        catch (e: AEADBadTagException) { return SessionLoad.RequiresSignIn(UnreadableReason.CORRUPTED) }
        catch (e: java.io.IOException) { return SessionLoad.RequiresSignIn(UnreadableReason.CORRUPTED) }
        catch (e: java.security.GeneralSecurityException) { return SessionLoad.RequiresSignIn(UnreadableReason.CORRUPTED) }
        try {
            DataInputStream(plain.inputStream()).use { input ->
                val stored = AccountId.parse(input.readUTF())
                if (stored != account) return SessionLoad.RequiresSignIn(UnreadableReason.WRONG_ACCOUNT)
                val method = runCatching { AuthMethod.valueOf(input.readUTF()) }.getOrElse { return SessionLoad.RequiresSignIn(UnreadableReason.CORRUPTED) }
                val masked = input.readUTF()
                val expires = Instant.ofEpochMilli(input.readLong())
                return SessionLoad.Found(AuthSession(Identity(account, method, masked), input.readUTF(), expires))
            }
        } catch (e: java.io.IOException) { return SessionLoad.RequiresSignIn(UnreadableReason.CORRUPTED) }
        finally { plain.fill(0) }
    }

    /** Removes the stored session and its key. Idempotent; never touches the account's calendar database. */
    override fun clear(account: AccountId) {
        file(account).delete()
        File(directory, file(account).name + ".tmp").delete()
        cipher.deleteKey(alias(account))
    }
}

/** Outcome of reading the stored session at app start. */
sealed interface SessionRestore {
    data object NoSession : SessionRestore
    data class Restored(val state: com.turnocontrol.domain.auth.AuthState) : SessionRestore
    /** Unreadable (key lost, tampered, unknown format): deleted; the user signs in again. The calendar data is untouched. */
    data class SignInAgain(val account: AccountId, val reason: UnreadableReason) : SessionRestore
}

suspend fun restoreStoredSession(manager: com.turnocontrol.domain.auth.AuthManager, vault: EncryptedSessionVault, account: AccountId): SessionRestore =
    when (val loaded = vault.load(account)) {
        SessionLoad.Missing -> SessionRestore.NoSession
        is SessionLoad.Found -> SessionRestore.Restored(manager.restore(loaded.session))
        is SessionLoad.RequiresSignIn -> { vault.clear(account); SessionRestore.SignInAgain(account, loaded.reason) }
    }

/** Production location: never backed up (noBackupFilesDir), keys in the Android Keystore. Not wired into the app yet. */
object SessionVaults {
    fun forContext(context: android.content.Context) = EncryptedSessionVault(File(context.noBackupFilesDir, "sessions"), KeystoreSessionCipher())
}
